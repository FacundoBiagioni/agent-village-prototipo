export type IconName = keyof typeof ICONS;

/** Dibuja el ícono con el color del texto (currentColor). Decorativo: el texto del link o botón lo nombra. */
export function PixelIcon({ name, size = 20, className }: { name: IconName; size?: number; className?: string }) {
  const d = ICONS[name].flatMap((row, y) => [...row].map((c, x) => (c === "#" ? `M${x} ${y}h1v1h-1z` : ""))).join("");
  return (
    <svg viewBox="0 0 10 10" width={size} height={size} aria-hidden shapeRendering="crispEdges" className={className}>
      <path d={d} fill="currentColor" />
    </svg>
  );
}
