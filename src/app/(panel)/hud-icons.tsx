const FILL: Record<Tone, string> = { K: "var(--ico-line, var(--hud-line))", M: "var(--ic)", L: "color-mix(in oklab, var(--ic) 45%, white)", S: "color-mix(in oklab, var(--ic) 68%, black)", W: "#fffdf6" };

export type HudIconName = keyof typeof ICONS;
export function HudIcon({ name, size = 32 }: { name: string; size?: number }) {
  const ic = ICONS[name] ?? ICONS.gear;
  return (
    <span className="hud-ico" style={{ ["--ic" as string]: ic.color }} aria-hidden>
      <svg viewBox="0 0 16 16" width={size} height={size} shapeRendering="crispEdges">
        {ic.art.map(([t, x, y, w, h], i) => (
          <rect key={i} x={x} y={y} width={w} height={h} fill={FILL[t]} />
        ))}
      </svg>
      <span className="hud-ti">{ic.text}</span>
    </span>
  );
}
